  async connectMetaMask() {
    if (typeof window.ethereum !== 'undefined') {
      try {
        const accounts = await window.ethereum.request({ method: 'eth_requestAccounts' });
        if (accounts.length > 0) {
          const oldAddr = this.myProfile.address;
          this.currentAccount = accounts[0];
          this.myProfile.address = accounts[0];
          this.isMetaMaskConnected = true;

          try {
            localStorage.setItem('fairshare_device_profile_v2', JSON.stringify(this.myProfile));
          } catch {}

          // Update member address in all groups
          this.groups.forEach(grp => {
            const m = grp.members.find(mem => mem.address.toLowerCase() === oldAddr.toLowerCase());
            if (m) {
              m.address = accounts[0];
            } else if (!grp.members.some(mem => mem.address.toLowerCase() === accounts[0].toLowerCase())) {
              grp.members.push({
                address: accounts[0],
                name: this.myProfile.name,
                role: 'MEMBER',
                avatar: this.myProfile.avatar,
                pin: this.myProfile.pin,
                joinedAt: Date.now(),
              });
            }
          });

          this.saveState();
          return { success: true, address: accounts[0] };
        }
      } catch (err) {
        console.error('MetaMask connection error:', err);
        return { success: false, error: err.message };
      }
    } else {
      return { success: false, error: 'MetaMask is not installed in this browser.' };
    }
  }

