/**
 * Get or create unique device user profile stored locally on this machine/phone
 */
export function getDeviceProfile() {
  const profileKey = 'fairshare_device_profile_v2';
  try {
    const stored = localStorage.getItem(profileKey);
    if (stored) {
      const parsed = JSON.parse(stored);
      if (parsed.name && !parsed.name.startsWith('User-')) {
        return parsed;
      }
    }
  } catch {}

  const randomWallet = ethers.Wallet.createRandom();

  const profile = {
    address: randomWallet.address,
    name: 'Eshwar (Admin)',
    avatar: '👑',
    tokenBalance: 75000, // ₹750.00 FSINR testnet tokens
    ethBalance: '1.0 ETH',
    pin: '1234',
    upiId: 'eshwar@okhdfcbank',
    isAutoGenerated: true,
  };

  try {
    localStorage.setItem(profileKey, JSON.stringify(profile));
  } catch {}

  return profile;
}

