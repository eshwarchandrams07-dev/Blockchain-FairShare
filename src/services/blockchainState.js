/**
 * Get or create unique device user profile stored locally on this machine/phone
 */
export function getDeviceProfile() {
  const profileKey = 'fairshare_device_profile_v2';
  try {
    const stored = localStorage.getItem(profileKey);
    if (stored) {
      const parsed = JSON.parse(stored);
      if (parsed.name && parsed.address) {
        if (!parsed.privateKey) {
          parsed.privateKey = ethers.Wallet.createRandom().privateKey;
          try {
            localStorage.setItem(profileKey, JSON.stringify(parsed));
          } catch {}
        }
        return parsed;
      }
    }
  } catch {}

  const randomWallet = ethers.Wallet.createRandom();
  const shortId = randomWallet.address.slice(2, 6).toLowerCase();
  const isHost = isOriginalHostDevice();

  const profile = {
    address: randomWallet.address,
    privateKey: randomWallet.privateKey,
    name: isHost ? 'Eshwar (Admin)' : `Phone User (${shortId})`,
    avatar: isHost ? '👑' : MEMBER_AVATARS[Math.floor(Math.random() * MEMBER_AVATARS.length)],
    tokenBalance: isHost ? 75000 : 50000, // Host gets ₹750, joining device gets ₹500
    ethBalance: '1.0 ETH',
    pin: isHost ? '1234' : String(1000 + Math.floor(Math.random() * 9000)),
    upiId: isHost ? 'eshwar@okhdfcbank' : `phone.${shortId}@upi`,
    isAutoGenerated: true,
  };

  try {
    localStorage.setItem(profileKey, JSON.stringify(profile));
  } catch {}

  return profile;
}

