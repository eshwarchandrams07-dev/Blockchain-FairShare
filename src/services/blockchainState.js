  approveExpense(groupId, expenseId) {
    const exp = this.expenses.find(e => e.id === expenseId && e.groupId === groupId);
    if (!exp) throw new Error('Expense not found');
    if (exp.status !== EXPENSE_STATUS.PENDING_APPROVAL) throw new Error('Expense not pending approval');

    if (!exp.approvals.some(a => a.toLowerCase() === this.currentAccount.toLowerCase())) {
      exp.approvals.push(this.currentAccount);
    }

    const group = this.groups.find(g => g.id === groupId);
    const totalParticipants = exp.shares.length;
    let quorumReached = false;

    if (group.approvalPolicy === APPROVAL_POLICIES.ADMIN_ONLY) {
      const callerRole = group.members.find(m => m.address.toLowerCase() === this.currentAccount.toLowerCase())?.role;
      if (callerRole === 'ADMIN') quorumReached = true;
    } else if (group.approvalPolicy === APPROVAL_POLICIES.UNANIMOUS_VOTE) {
      if (exp.approvals.length >= totalParticipants) quorumReached = true;
    } else if (group.approvalPolicy === APPROVAL_POLICIES.MAJORITY_VOTE) {
      if (exp.approvals.length > Math.floor(totalParticipants / 2)) quorumReached = true;
    }

    this.addAuditLog(
      groupId,
      'EXPENSE_APPROVED_VOTE',
      this.currentAccount,
      this.getMyProfile().name,
      `Cast approval vote on Expense #${expenseId} (${exp.approvals.length}/${totalParticipants} votes)`
    );

    if (quorumReached) {
      exp.status = EXPENSE_STATUS.APPROVED;
      this.addAuditLog(
        groupId,
        'EXPENSE_CONFIRMED',
        this.currentAccount,
        'Smart Contract Consensus',
        `Approval threshold met for Expense #${expenseId}. Ledger balances updated.`
      );
    }

    this.saveState();
    return exp;
  }

  castConsensusVote({ groupId, expenseId, voterAddress, pin, agreed, reason }) {
    const exp = this.expenses.find(e => Number(e.id) === Number(expenseId) && Number(e.groupId) === Number(groupId));
    if (!exp) throw new Error(`Expense #${expenseId} not found in Group #${groupId}`);

    if (exp.status !== EXPENSE_STATUS.PENDING_APPROVAL) {
      throw new Error(`Consensus Block for Expense #${expenseId} is already ${STATUS_LABELS[exp.status] || 'closed'}.`);
    }

    const group = this.groups.find(g => Number(g.id) === Number(groupId));
    const groupMember = group?.members.find(m => m.address.toLowerCase() === voterAddress.toLowerCase());

    const isMyDevice = voterAddress.toLowerCase() === this.myProfile.address.toLowerCase();
    const expectedPin = isMyDevice ? this.myProfile.pin : (groupMember?.pin || '1234');
    const voterName = isMyDevice ? this.myProfile.name : (groupMember?.name || voterAddress.substring(0, 8));

    // ANTI-CHEAT SECURITY CHECK: Verify Voter PIN
    if (!pin || pin.trim() !== expectedPin) {
      throw new Error(`Anti-Cheat Security Failure: Incorrect PIN for ${voterName}! Only the genuine account owner on their device can sign this consensus vote.`);
    }

    if (!exp.votes) {
      exp.votes = exp.shares.map(s => ({
        participant: s.participant,
        name: s.name,
        amount: s.amount,
        status: s.participant.toLowerCase() === exp.payer.toLowerCase() ? 'AGREED' : 'PENDING',
        reason: s.participant.toLowerCase() === exp.payer.toLowerCase() ? 'Payer Submission' : '',
        signature: s.participant.toLowerCase() === exp.payer.toLowerCase() ? generateTxHash() : null,
        timestamp: s.participant.toLowerCase() === exp.payer.toLowerCase() ? exp.createdAt : null,
        pinVerified: true,
      }));
    }

    const voteItem = exp.votes.find(v => v.participant.toLowerCase() === voterAddress.toLowerCase());
    if (!voteItem) {
      throw new Error(`Address ${voterAddress} is not a listed participant on Expense #${expenseId}`);
    }

    const signature = generateTxHash();
    voteItem.status = agreed ? 'AGREED' : 'REJECTED';
    voteItem.reason = reason || (agreed ? 'Confirmed participant share' : 'Disputed share allocation');
    voteItem.signature = signature;
    voteItem.timestamp = Date.now();
    voteItem.pinVerified = true;

    if (agreed) {
      if (!exp.approvals.some(a => a.toLowerCase() === voterAddress.toLowerCase())) {
        exp.approvals.push(voterAddress);
      }
      exp.rejections = exp.rejections.filter(r => r.toLowerCase() !== voterAddress.toLowerCase());
    } else {
      if (!exp.rejections.some(r => r.toLowerCase() === voterAddress.toLowerCase())) {
        exp.rejections.push(voterAddress);
      }
      exp.approvals = exp.approvals.filter(a => a.toLowerCase() !== voterAddress.toLowerCase());
    }

    const totalParticipants = exp.shares.length;
    const agreedCount = exp.votes.filter(v => v.status === 'AGREED').length;
    const rejectedCount = exp.votes.filter(v => v.status === 'REJECTED').length;

    let quorumReached = false;
    let blockRejected = false;

    if (group?.approvalPolicy === APPROVAL_POLICIES.ADMIN_ONLY) {
      const callerRole = group.members.find(m => m.address.toLowerCase() === voterAddress.toLowerCase())?.role;
      if (callerRole === 'ADMIN') {
        if (agreed) quorumReached = true;
        else blockRejected = true;
      }
    } else if (group?.approvalPolicy === APPROVAL_POLICIES.UNANIMOUS_VOTE) {
      if (rejectedCount > 0) blockRejected = true;
      else if (agreedCount >= totalParticipants) quorumReached = true;
    } else {
      // Majority vote (> 50%)
      if (agreedCount > Math.floor(totalParticipants / 2)) {
        quorumReached = true;
      } else if (rejectedCount >= Math.ceil(totalParticipants / 2)) {
        blockRejected = true;
      }
    }

    this.addAuditLog(
      groupId,
      agreed ? 'CONSENSUS_VOTE_AGREED' : 'CONSENSUS_VOTE_REJECTED',
      voterAddress,
      voterName,
      `${voterName} signed consensus vote [${agreed ? 'AGREED' : 'REJECTED'}] on Expense #${expenseId} [Signature: ${signature.substring(0, 10)}...]. ${reason ? 'Reason: "' + reason + '"' : ''}`
    );

    if (quorumReached) {
      exp.status = EXPENSE_STATUS.APPROVED;
      this.addAuditLog(
        groupId,
        'CONSENSUS_BLOCK_SEALED',
        voterAddress,
        'Consensus Protocol',
        `Consensus Block #${expenseId} SEALED & VERIFIED with ${agreedCount}/${totalParticipants} approvals. Financial balances updated on-chain.`
      );
    } else if (blockRejected) {
      exp.status = EXPENSE_STATUS.REJECTED;
      exp.rejectReason = reason || 'Quorum rejected by participant vote.';
      this.addAuditLog(
        groupId,
        'CONSENSUS_BLOCK_REJECTED',
        voterAddress,
        'Consensus Protocol',
        `Consensus Block #${expenseId} REJECTED by participant objection. Payment balances frozen.`
      );
    }

    this.saveState();

    liveSync.broadcast({
      type: 'CONSENSUS_VOTE_NOTIFICATION',
      groupId,
      expenseId,
      voterAddress,
      voterName,
      agreed,
      reason,
      quorumReached,
      blockRejected,
      expenseTitle: exp.title,
    });

    if (quorumReached) {
      playChimeSound('success');
    } else if (blockRejected) {
      playChimeSound('alert');
    } else {
      playChimeSound('notification');
    }

    return exp;
  }

