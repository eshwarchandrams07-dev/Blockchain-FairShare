/**
 * Check if this device is the original host (first-ever install) vs a joining device
 */
function isOriginalHostDevice() {
  try {
    // If there's already stored state, this is an existing device
    const stored = localStorage.getItem('fairshare_blockchain_v5_publicledger');
    if (stored) return true;
    // If there's a profile already, this is an existing device
    const profile = localStorage.getItem('fairshare_device_profile_v2');
    if (profile) return true;
    // Check if there are URL join params (this is a joining device)
    if (typeof window !== 'undefined') {
      const params = new URLSearchParams(window.location.search);
      if (params.get('joinGroup') || params.get('join') || params.get('groupId') || params.get('ledgerId') || params.get('id') || params.get('pvtLedger')) {
        return false;
      }
      // If accessed via LAN IP or external hostname (not localhost/127.0.0.1), this is a remote joining device
      const host = window.location.hostname;
      if (host && host !== 'localhost' && host !== '127.0.0.1') {
        return false;
      }
    }
  } catch {}
  // First-time load on localhost without join params = host device
  return true;
}

