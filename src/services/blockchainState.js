  joinGroup(groupId, inviteKey = null, ledgerId = null, memberDisplayName = null) {
    let grp = null;

    // 1. If a ledgerId was provided, look up group by ledgerId across all groups first
    if (ledgerId && typeof ledgerId === 'string' && ledgerId.trim()) {
      const cleanLedgerId = ledgerId.trim().toUpperCase();
      const cleanAlpha = cleanLedgerId.replace(/[^A-Z0-9]/g, '');
      if (cleanLedgerId === 'PUB-101' || cleanLedgerId === 'PUBLIC' || cleanAlpha === 'PUB101' || cleanAlpha === 'PUBLIC') {
        grp = this.groups.find(g => String(g.id) === '1' || Number(g.id) === 1 || !g.isPrivate);
      } else {
        grp = this.groups.find(g => {
          if (!g.ledgerId && !g.id) return false;
          const gClean = (g.ledgerId || String(g.id)).trim().toUpperCase();
          return gClean === cleanLedgerId || (cleanAlpha && gClean.replace(/[^A-Z0-9]/g, '') === cleanAlpha);
        });
      }
    }

    // 2. If not found by ledgerId, look up by groupId
    if (!grp && groupId !== null && groupId !== undefined && String(groupId).trim() !== '') {
      grp = this.groups.find(g => String(g.id) === String(groupId) || (!isNaN(Number(g.id)) && !isNaN(Number(groupId)) && Number(g.id) === Number(groupId)));
    }

    if (!grp) {
      // Group not yet loaded in local state; request sync from peers
      const numId = (groupId !== null && groupId !== undefined && !isNaN(Number(groupId))) ? Number(groupId) : null;
      this.pendingJoinGroupId = numId;
      this.pendingJoinKey = inviteKey;
      this.pendingJoinLedgerId = ledgerId ? ledgerId.trim().toUpperCase() : null;
      this.pendingMemberDisplayName = memberDisplayName;
      if (numId) {
        this.currentGroupId = numId;
      }
      this._savePendingJoinStorage();

      // Broadcast REQUEST_SYNC — if WebSocket isn't connected yet, queue a retry
      const doSync = () => {
        liveSync.broadcast({
          type: 'REQUEST_SYNC',
          targetGroupId: numId,
          targetLedgerId: this.pendingJoinLedgerId,
        });
      };
      doSync();
      if (liveSync.getStatus() !== 'CONNECTED') {
        liveSync.onceConnected(() => doSync());
      }
      return { success: false, pending: true, message: `Searching network for private ledger ${ledgerId || groupId || ''}... Syncing from peer host...` };
    }

    const targetGroupId = grp.id;
    this.pendingJoinGroupId = null;
    this.pendingJoinKey = null;
    this.pendingJoinLedgerId = null;
    this.pendingMemberDisplayName = null;
    this._clearPendingJoinStorage();

    // If new device provided a custom display name
    if (memberDisplayName && memberDisplayName.trim()) {
      this.myProfile.name = memberDisplayName.trim();
      try {
        localStorage.setItem('fairshare_device_profile_v2', JSON.stringify(this.myProfile));
      } catch {}
    }

    // Public group: open for anyone to explore or join
    if (!grp.isPrivate) {
      this.unlockGroup(targetGroupId);
      this.ensureMemberInGroup(grp);
      this.currentGroupId = targetGroupId;
      this.saveState();
      return { success: true, group: grp, isPublic: true };
    }

    // Check if group is already unlocked and this user is already a verified member
    const alreadyUnlocked = this.isGroupUnlocked(targetGroupId);
    const alreadyJoined = this.isUserJoinedToGroup(grp);

    if (alreadyUnlocked && alreadyJoined) {
      this.currentGroupId = targetGroupId;
      this.saveState();
      return { success: true, group: grp };
    }

    // Private group: verify Ledger ID and Password
    if (inviteKey || ledgerId) {
      const expectedPassword = (grp.password || grp.inviteCode || '').trim().toUpperCase();
      const providedPassword = (inviteKey || '').trim().toUpperCase();
      const cleanExpectedPass = expectedPassword.replace(/[^A-Z0-9]/g, '');
      const cleanProvidedPass = providedPassword.replace(/[^A-Z0-9]/g, '');

      const isPassValid = expectedPassword && (providedPassword === expectedPassword || cleanProvidedPass === cleanExpectedPass);

      // Verify Ledger ID if group has one
      let isIdValid = true;
      if (grp.ledgerId && ledgerId) {
        const expectedId = (grp.ledgerId || '').trim().toUpperCase();
        const providedId = (ledgerId || '').trim().toUpperCase();
        const cleanExpectedId = expectedId.replace(/[^A-Z0-9]/g, '');
        const cleanProvidedId = providedId.replace(/[^A-Z0-9]/g, '');
        isIdValid = (providedId === expectedId || cleanProvidedId === cleanExpectedId);
      }

      if (isPassValid && isIdValid) {
        this.unlockGroup(targetGroupId);
        this.ensureMemberInGroup(grp);
        this.currentGroupId = targetGroupId;

        this.addAuditLog(
          targetGroupId,
          'MEMBER_JOINED',
          this.myProfile.address,
          this.myProfile.name,
          `${this.myProfile.name} verified credentials (ID: ${grp.ledgerId || 'OK'} & Password) and entered private ledger.`
        );

        this.saveState();
        return { success: true, group: grp };
      } else {
        const errDetails = !isIdValid ? 'Incorrect Ledger ID.' : 'Incorrect Password.';
        return {
          success: false,
          error: `${errDetails} Access denied. Outsiders cannot join this private ledger.`
        };
      }
    }

    // No key provided and not unlocked
    return {
      success: false,
      error: 'This ledger is private. Please enter the correct Ledger ID and Password.'
    };
  }

  /**
   * Enter any private ledger directly by Ledger ID and Password
   * Supports immediate cloud database lookup if ledger is not yet in local browser storage
   */
  async enterLedgerByCredentials(ledgerId, password, memberDisplayName = null) {
    if (!ledgerId || !ledgerId.trim()) {
      return { success: false, error: 'Please enter the Private Ledger ID (e.g. APT-402, GOA-2026).' };
    }
    if (!password || !password.trim()) {
      return { success: false, error: 'Please enter the Security Password for this private ledger.' };
    }

    const cleanId = ledgerId.trim().toUpperCase();
    const cleanPass = password.trim();

    // 1. Check local in-memory groups
    let res = this.joinGroup(null, cleanPass, cleanId, memberDisplayName);
    if (res && res.success) return res;

    // 2. If not found locally, query the permanent cloud database (/api/ledger-state)
    if (!res || !res.success) {
      try {
        const remoteRes = await fetch('/api/ledger-state');
        if (remoteRes.ok) {
          const data = await remoteRes.json();
          if (data && data.state && Array.isArray(data.state.groups)) {
            this.mergeRemoteState(data.state);
            this.saveState(true);
            res = this.joinGroup(null, cleanPass, cleanId, memberDisplayName);
            if (res && res.success) return res;
          }
        }
      } catch (err) {
        console.warn('Notice querying cloud database for private ledger:', err);
      }
    }

    return res;
  }

